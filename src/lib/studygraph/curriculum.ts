function q(
  conceptId: string,
  difficulty: Question["difficulty"],
  type: Question["type"],
  prompt: string,
  choices: string[] | undefined,
  answer: Question["answer"],
  explanation: string,
  misconception: string,
  tolerance?: number,
): Question {
  return {
    id: `${conceptId}-${difficulty}-${prompt.length}-${(choices?.length ?? 0)}`,
    conceptId,
    type,
    difficulty,
    prompt,
    choices,
    answer,
    explanation,
    misconception,
    tolerance,
  };
}

