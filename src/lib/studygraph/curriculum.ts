function nextExamDate(month: number, day: number) {
  const now = new Date();
  const year = now.getMonth() > month ? now.getFullYear() + 1 : now.getFullYear();
  return new Date(Date.UTC(year, month, day)).toISOString().slice(0, 10);
}

